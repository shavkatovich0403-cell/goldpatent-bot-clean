def search_classes(query: str, lang: str = "uz") -> list:
    """Klasslarni qidirish"""
    query = query.lower().strip()
    if not query:
        return []
    
    results = []
    
    # Raqam bo'yicha qidirish
    if query.isdigit():
        num = int(query)
        for cls in NICE_CLASSES:
            if cls[0] == num:
                results.append(cls)
        return results
    
    # So'z bo'yicha qidirish
    for cls in NICE_CLASSES:
        name = cls[1].get(lang, cls[1]["uz"]).lower()
        desc = cls[2].get(lang, cls[2]["uz"]).lower()
        if query in name or query in desc:
            results.append(cls)
    
    return results


def get_class_by_number(num: int) -> list | None:
    """Raqam bo'yicha klassni qaytaradi"""
    for cls in NICE_CLASSES:
        if cls[0] == num:
            return cls
    return None


def get_classes_by_type(class_type: str) -> list:
    """Tovarlar yoki xizmatlarni qaytaradi"""
    return [cls for cls in NICE_CLASSES if cls[3] == class_type]
